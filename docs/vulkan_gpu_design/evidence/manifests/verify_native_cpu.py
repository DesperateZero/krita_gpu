"""Replay the frozen CPU comparison from the checked-out evidence in a temporary directory."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tarfile
from tempfile import TemporaryDirectory

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def checked(data, expected, label):
    if digest(data) != expected:
        raise ValueError(f"Wrong SHA-256 for {label}")
    return data


def main():
    manifest = json.loads((HERE / "native-cpu-0fd96.json").read_text())
    source = REPO / manifest["root"]
    with TemporaryDirectory() as tmp:
        dest = Path(tmp)
        for item in manifest["items"]:
            path = dest / item["path"]
            archive, member_marker, member = item["source"].partition("!")
            if member_marker:
                with tarfile.open(source / archive) as tar:
                    data = tar.extractfile(member).read()
            else:
                data = (source / archive).read_bytes()
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(checked(data, item["sha256"], item["path"]))

        outputs = {name: (dest / name).read_bytes() for name in (
            "FORECAST.json", "VALIDATION_PROTOCOL.json", "JOINT_RESULT.json", "FRESH_RESULT.json"
        )}
        # The preregistered block schedule is an input to forecast. Only its
        # forecast digest is regenerated by the frozen analyzer.
        protocol_path = dest / "VALIDATION_PROTOCOL.json"
        protocol = json.loads(protocol_path.read_text())
        protocol["forecast_sha256"] = None
        protocol_path.write_text(json.dumps(protocol))
        for name in ("FORECAST.json", "JOINT_RESULT.json", "FRESH_RESULT.json"):
            (dest / name).unlink()
        for stage in ("forecast", "validation", "fresh"):
            subprocess.run([sys.executable, str(dest / "analyze-joint-price.py"), stage],
                           cwd=dest, stdout=subprocess.DEVNULL, check=True)
        for name, expected in outputs.items():
            checked((dest / name).read_bytes(), digest(expected), name)
        sizes = {name: len(json.loads((dest / name / "RUNS.json").read_text()))
                 for name in ("calibration", "validation", "fresh")}
        print(json.dumps({"samples": sizes, "byte_identical": list(outputs)}))


if __name__ == "__main__":
    main()
